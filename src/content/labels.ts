export const socGroup = (code: string) => SOC_GROUP_BY_MAJOR[code.slice(0, 2)] ?? '기타'
export const socKo = (code: string, fallback = code) => SOC_KO[code]?.[0] ?? fallback

export function socOptions(socs: { code: string; title: string }[]): Opt[] {
  return socs
    .map((s) => ({ value: s.code, label: socKo(s.code, s.title), sub: s.title, group: socGroup(s.code), kw: SOC_KO[s.code]?.[1] }))
    .sort((a, b) => SOC_GROUPS.indexOf(a.group) - SOC_GROUPS.indexOf(b.group) || a.label.localeCompare(b.label, 'ko'))
}

